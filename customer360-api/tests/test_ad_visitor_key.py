"""The admin plane's visitor key derivation must equal the ad server's.

Both services load specs/003-ad-personalization-engine/contracts/visitor-key-test-vectors.json
(generated by running the ad server's implementation), so neither can change alone.
"""

import json
from pathlib import Path

import pytest

from core.utils import ad_visitor_key as avk

VECTORS_PATH = (
    Path(__file__).resolve().parents[2]
    / "docs" / "ad-personalization" / "contracts" / "visitor-key-test-vectors.json"
)


@pytest.fixture(scope="module")
def vectors():
    if not VECTORS_PATH.exists():
        pytest.skip("shared test vectors not available in this checkout")
    return json.loads(VECTORS_PATH.read_text())


def test_every_shared_vector_matches(vectors):
    for case in vectors["vectors"]:
        secret = avk.tenant_secret(case["master_secret"], case["tenant_id"])
        assert secret.hex() == case["tenant_secret_hex"]
        key = avk.visitor_key(case["tenant_id"], case["leovid"], case["master_secret"])
        assert key.hex() == case["expected_key_hex"]
        assert len(key) == avk.KEY_BYTES == 16


def test_unusable_visitor_ids_are_rejected(vectors):
    for bad in vectors["invalid_visitor_ids"]:
        with pytest.raises(ValueError):
            avk.visitor_key(1, bad, "s")
    with pytest.raises(ValueError):
        avk.visitor_key(1, "x" * (vectors["max_visitor_id_length"] + 1), "s")
    assert len(avk.visitor_key(1, "x" * vectors["max_visitor_id_length"], "s")) == 16


def test_the_same_visitor_gets_different_keys_in_different_tenants(vectors):
    first, second = vectors["vectors"][0], vectors["vectors"][1]
    assert first["expected_key_hex"] != second["expected_key_hex"]


def test_fingerprint_is_the_first_four_bytes_only():
    assert avk.fingerprint(bytes(range(16))) == "00010203"
    assert avk.fingerprint(None) is None


def test_the_secret_comes_from_the_environment_with_a_development_default(monkeypatch):
    for name in ("AD_VISITOR_KEY_MASTER_SECRET", "c360_PROMOTION_VISITOR_KEY_MASTER_SECRET", "c360_PROMOTION_ENVIRONMENT"):
        monkeypatch.delenv(name, raising=False)

    # Development with nothing configured: the fixed development-only value.
    assert avk.configured_master_secret() == "development-only-visitor-key-secret"

    # The ad server's own variable is honoured so one value serves both services.
    monkeypatch.setenv("c360_PROMOTION_VISITOR_KEY_MASTER_SECRET", "shared")
    assert avk.configured_master_secret() == "shared"

    # An explicit admin-plane value wins.
    monkeypatch.setenv("AD_VISITOR_KEY_MASTER_SECRET", "admin")
    assert avk.configured_master_secret() == "admin"


def test_outside_development_a_missing_secret_means_no_key(monkeypatch):
    for name in ("AD_VISITOR_KEY_MASTER_SECRET", "c360_PROMOTION_VISITOR_KEY_MASTER_SECRET"):
        monkeypatch.delenv(name, raising=False)
    monkeypatch.setenv("c360_PROMOTION_ENVIRONMENT", "production")

    assert avk.configured_master_secret() is None
    with pytest.raises(avk.VisitorKeyUnavailable):
        avk.visitor_key(1, "someone")
